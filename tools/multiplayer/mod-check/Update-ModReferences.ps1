# Rebuilds mod-references.txt: every type, method and field of this build (Assembly-CSharp, Memoria.Prime) the Black
# Waltz mod's compiled scripts (Memoria.Scripts.HadesWorkshopMod.dll) use directly, with its signature.
# Test-ModReferences.ps1 then checks a build still has each of them. See README.md.
#
#   .\Update-ModReferences.ps1                  # the mod's main branch on GitHub (needs gh, signed in with access)
#   .\Update-ModReferences.ps1 -Ref <sha|tag>   # another commit
#   .\Update-ModReferences.ps1 -ModPath <dir>   # a local checkout of the mod instead
#
# It reads the mod's DLL against the current build in Output\ (run build.ps1 -SkipModCheck first if needed).
param(
    [string]$Ref = 'main',
    [string]$ModPath,
    [string]$Repo = 'Vuux2/ff9-black-waltz-mod'
)
$ErrorActionPreference = 'Stop'
$dllRel = 'mod/HadesWorkshopMod/StreamingAssets/Scripts/Memoria.Scripts.HadesWorkshopMod.dll'
$root = Resolve-Path (Join-Path $PSScriptRoot '..\..\..')
$outFile = Join-Path $PSScriptRoot 'mod-references.txt'

# ---- Get the mod's DLL ----------------------------------------------------------------------------------------
# Copied to a temporary folder of its own: loading it locks the file until this process ends
$work = Join-Path ([IO.Path]::GetTempPath()) ("mod-references-" + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $work | Out-Null
$modDll = Join-Path $work 'Memoria.Scripts.HadesWorkshopMod.dll'
if ($ModPath) {
    $src = Join-Path $ModPath $dllRel
    if (-not (Test-Path $src)) { $src = $ModPath }
    if (-not (Test-Path $src -PathType Leaf)) { throw "No mod DLL at $(Join-Path $ModPath $dllRel)" }
    Copy-Item $src $modDll
    $commit = (& git -C $ModPath rev-parse HEAD 2>$null)
    $dirty = (& git -C $ModPath status --porcelain -- $dllRel 2>$null)
    $origin = if ($commit) { "$Repo @ $commit (local checkout$(if ($dirty) { ', with uncommitted changes' }))" } else { 'a local file (not a git checkout)' }
}
else {
    if (-not (Get-Command gh -ErrorAction SilentlyContinue)) { throw 'gh (GitHub CLI) not found: install it, or use -ModPath' }
    $commit = (& gh api "repos/$Repo/commits/$Ref" -q .sha)
    if ($LASTEXITCODE -ne 0 -or -not $commit) { throw "Can't read $Repo at '$Ref' (gh auth status? access to the repo?)" }
    $sha = (& gh api "repos/$Repo/contents/$dllRel`?ref=$commit" -q .sha)
    $b64 = (& gh api "repos/$Repo/git/blobs/$sha" -q .content)
    [IO.File]::WriteAllBytes($modDll, [Convert]::FromBase64String(($b64 -join '')))
    $origin = "$Repo @ $commit"
}
Write-Host "Reading the mod's compiled scripts from $origin"

# ---- Extract --------------------------------------------------------------------------------------------------
Add-Type -Path (Join-Path $PSScriptRoot 'ModReferences.cs')
[ModReferences]::Setup([string[]]@((Join-Path $root 'Output'), (Join-Path $root 'References'), $work))
$r = [ModReferences]::Extract($modDll)
if ($r.Problems.Count -gt 0) {
    Write-Host ''
    Write-Host "The mod's DLL uses things the build in Output\ doesn't have, so the list can't be made from it:" -ForegroundColor Yellow
    $r.Problems | Sort-Object -Unique | ForEach-Object { Write-Host "  $_" }
    Write-Host 'Either the build broke them (Test-ModReferences.ps1 with the old list names them), or the mod was built' -ForegroundColor Yellow
    Write-Host 'against a newer build: build that first.' -ForegroundColor Yellow
    exit 1
}
$rows = foreach ($kv in $r.Rows.GetEnumerator()) { "$($kv.Key)`t# $(@($kv.Value) -join ',')" }
$header = @(
    '# Generated by Update-ModReferences.ps1: do not edit by hand (see README.md).',
    "# Source: $origin",
    '# What the mod''s compiled scripts use of this build, by signature. Tab-separated, then # the mod types that use it:',
    '#   type    <assembly> <type>',
    '#   field   <assembly> <type> <name> static|instance public|nonpublic <field type>',
    '#   method  <assembly> <type> <name> static|instance public|nonpublic (<parameter types>) <return type> [`<generic arity>]',
    '#   ctor    <assembly> <type> .ctor  static|instance public|nonpublic (<parameter types>)',
    '# Generic parameters are written by position: !0 (the type''s), !!0 (the method''s).'
)
[IO.File]::WriteAllLines($outFile, [string[]]($header + $rows), (New-Object Text.UTF8Encoding $false))
$counts = $r.Rows.Keys | Group-Object { ($_ -split "`t")[0] } | ForEach-Object { "$($_.Count) $($_.Name)s" }
Write-Host "Wrote $($r.Rows.Count) references ($($counts -join ', ')) to $outFile"
Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
